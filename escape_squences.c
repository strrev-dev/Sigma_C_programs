// C program to demonstrate example of escape sequences
// Most popular Escape Sequences

// \\	\
// \"	"
// \'	'
// \?	?
// \a	Alert
// \b	Back space 
// \n	New Line
// \t	Horizontal tab
// \v	Vertical tab
// \r	Carriage return

#include <stdio.h>

int main() {
    printf("hellow\nworld\n");
    printf("hello \tworld\n");    
    printf("hello \bworld\n");    
    printf("hello \b world\n");    
    printf("hello \?world\n");    

}